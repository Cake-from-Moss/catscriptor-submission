package org.cfm.catscriptor.native.models

import java.io.Closeable

/**
 * Этап владеет ресурсами своей модели, загружает её лениво и освобождает ресурсы в [close].
 * Повторное закрытие безопасно. После закрытия использовать реализацию нельзя.
 * Будущий оркестратор должен закрыть модель одного этапа до загрузки следующей, даже при ошибке.
 * Реализации выполняют тяжёлую работу вне UI-потока, поддерживают отмену и передают ошибки
 * вызывающему коду; заранее подготовленная расшифровка недопустима даже как резервный результат.
 */
interface ModelResource : Closeable
