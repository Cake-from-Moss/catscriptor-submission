package org.cfm.catscriptor.domain.pipeline

interface UtteranceMerger {
    /**
     * Назначить спикера фрагменту ASR по пересечению интервалов и объединить соседние
     * реплики одного спикера, сохраняя текст и абсолютные границы аудио.
     * Если фрагмент содержит нескольких спикеров, этап диаризации (issue #6) должен
     * уточнить интервалы ходов и повторить ASR, а не делить текст по выдуманным меткам слов.
     * Вернуть отсортированные реплики. Реализация явно определяет поведение при равных
     * пересечениях и при их отсутствии. Перебивания не должны приводить к незаметному
     * дублированию или потере распознанного текста. Пустые результаты тишины не создают реплик.
     */
    suspend fun merge(asr: List<AsrSegment>, speakers: List<SpeakerSegment>): Transcript
}
